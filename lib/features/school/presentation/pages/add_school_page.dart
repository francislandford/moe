  Widget _buildSectionCard({
    required String title,
    required List<Widget> children,
  }) {
    return Card(
      elevation: 2,
      margin: const EdgeInsets.only(bottom: 24),
      shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(16)),
      child: Padding(
        padding: const EdgeInsets.all(20),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Text(
              title,
              style: Theme.of(context).textTheme.titleLarge?.copyWith(
                color: AppColors.primary,
                fontFamily: 'RobotoSlabBold',
              ),
            ),
            const SizedBox(height: 20),
            ...children,
          ],
        ),
      ),
    );
  }

  Widget _dropdown({
    required String label,
    required String? value,
    List<String> items = const [],
    required ValueChanged<String?> onChanged,
    String? Function(String?)? validator,
  }) {
    return DropdownButtonFormField<String>(
      value: value,
      decoration: const InputDecoration(
        border: OutlineInputBorder(),
        contentPadding: EdgeInsets.symmetric(horizontal: 16, vertical: 16),
      ).copyWith(labelText: label),
      items:
      items.map((item) {
        return DropdownMenuItem<String>(value: item, child: Text(item));
      }).toList(),
      onChanged: onChanged,
      validator: validator,
    );
  }

  Widget _yearDropdown() {
    final currentYear = DateTime.now().year;
    final years =
    List.generate(
      currentYear - 1820,
          (index) => (currentYear - index).toString(),
    )..sort((a, b) => b.compareTo(a));

    return DropdownButtonFormField<String>(
      value:
      _yearEstablishedController.text.isNotEmpty
          ? _yearEstablishedController.text
          : null,
      decoration: const InputDecoration(
        labelText: 'Year Established *',
        border: OutlineInputBorder(),
        contentPadding: EdgeInsets.symmetric(horizontal: 16, vertical: 16),
      ),
      items:
      years.map((year) {
        return DropdownMenuItem<String>(value: year, child: Text(year));
      }).toList(),
      onChanged: (value) {
        if (value != null) {
          _yearEstablishedController.text = value;
        }
      },
      validator:
      _hasConsent ? (v) => v == null ? 'Please select a year' : null : null,
    );
  }
